#!/usr/bin/env python3
"""Rewrite the [icon] block of templates/yazi-theme.toml.tpl from a Yazi preset.

    themes/yazi-icons.py <theme-dark.toml> [--version 26.9.1] [--template PATH]

The preset is yazi-config/preset/theme-dark.toml from the Yazi release you are
upgrading to. Every `fg = "#rrggbb"` in its [icon] tables is replaced by a
palette placeholder chosen by hue, glyphs and rule order stay untouched, and the
result lands between the BEGIN/END markers in the template.
"""
import argparse
import colorsys
import re
import sys
from pathlib import Path

BEGIN = "# BEGIN yazi-icons (generated by themes/yazi-icons.py; do not edit by hand)"
END = "# END yazi-icons"
HUES = {"red": 0, "orange": 30, "yellow": 58, "green": 120, "cyan": 182,
        "blue": 208, "magenta": 295}
# Conds that are pinned instead of mapped by hue.
PINNED = {"dir": "blue", "dir & hovered": "blue", "exec": "green"}


def role(hex_color):
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    if s < 0.2 and v > 0.9:
        return "fg"
    if s < 0.2 or (s < 0.35 and v < 0.4):
        return "fg_dim"
    deg = h * 360

    def dist(ref):
        d = abs(deg - ref) % 360
        return min(d, 360 - d)
    return min(HUES, key=lambda name: dist(HUES[name]))


def convert(line):
    cond = re.search(r'if = "([^"]*)"', line)
    pinned = PINNED.get(cond.group(1)) if cond else None
    return re.sub(r'fg = "(#[0-9a-fA-F]{6})"',
                  lambda m: 'fg = "{{%s}}"' % (pinned or role(m.group(1))), line)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("preset", type=Path)
    ap.add_argument("--version", default="26.9.1")
    ap.add_argument("--template", type=Path,
                    default=Path(__file__).resolve().parent / "templates/yazi-theme.toml.tpl")
    args = ap.parse_args()

    lines = args.preset.read_text().splitlines()
    try:
        start = lines.index("[icon]")
    except ValueError:
        sys.exit("no [icon] section in " + str(args.preset))
    body = []
    for line in lines[start:]:
        if body and line.startswith("[") and line != "[icon]":
            break
        if line.startswith("# : }}}"):
            break
        body.append(convert(line))
    while body and not body[-1].strip():
        body.pop()
    block = "\n".join([BEGIN, f"# Source: Yazi v{args.version} preset/theme-dark.toml [icon].",
                       "# Plain keys replace the preset lists; rule order is the preset's.",
                       *body, END])

    text = args.template.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    args.template.write_text(text)


if __name__ == "__main__":
    main()
